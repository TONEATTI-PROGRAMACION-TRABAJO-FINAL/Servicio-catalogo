-- Initial schema, written from the JPA entities. Hibernate only validates it (ddl-auto=validate).
-- The ids of the catalog are assigned by the cátedra, so they are not generated. The tables have no foreign keys
-- between them, like the entities.

CREATE TABLE professional_categories (
    id          BIGINT PRIMARY KEY,
    name        VARCHAR(255),
    description VARCHAR(255),
    enabled     BOOLEAN,
    created_at  TIMESTAMP(6) WITH TIME ZONE,
    updated_at  TIMESTAMP(6) WITH TIME ZONE
);

CREATE TABLE professionals (
    id          BIGINT PRIMARY KEY,
    category_id BIGINT,
    first_name  VARCHAR(255),
    last_name   VARCHAR(255),
    enabled     BOOLEAN,
    created_at  TIMESTAMP(6) WITH TIME ZONE,
    updated_at  TIMESTAMP(6) WITH TIME ZONE
);
CREATE INDEX ix_professionals_category_id ON professionals (category_id);

CREATE TABLE weekly_schedules (
    id                    BIGINT PRIMARY KEY,
    professional_id       BIGINT,
    day_of_week           VARCHAR(255),
    start_time            TIME,
    end_time              TIME,
    slot_duration_minutes INTEGER,
    enabled               BOOLEAN,
    created_at            TIMESTAMP(6) WITH TIME ZONE,
    updated_at            TIMESTAMP(6) WITH TIME ZONE
);
CREATE INDEX ix_weekly_schedules_professional_id ON weekly_schedules (professional_id);

-- A single row (id 1): the version of the local catalog. generated_at is NULL after an incremental version.
CREATE TABLE catalog_sync_state (
    id               BIGINT PRIMARY KEY,
    snapshot_version BIGINT,
    generated_at     TIMESTAMP(6) WITH TIME ZONE,
    synced_at        TIMESTAMP(6) WITH TIME ZONE
);

-- The unique eventId is what guarantees that a CatalogUpdated is processed once; the index serves the purge.
CREATE TABLE processed_catalog_events (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id     VARCHAR(255) NOT NULL,
    new_version  BIGINT NOT NULL,
    processed_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_processed_catalog_events_event_id UNIQUE (event_id)
);
CREATE INDEX ix_processed_catalog_events_processed_at ON processed_catalog_events (processed_at);
